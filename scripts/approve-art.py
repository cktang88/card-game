"""Approve drafts: convert art-drafts/<round>/<id>.png -> public/art/<id>.webp (768px wide).
Usage: python3 scripts/approve-art.py <round> id1 id2 ..."""
import sys
from PIL import Image
rnd, ids = sys.argv[1], sys.argv[2:]
for i in ids:
    im = Image.open(f"art-drafts/{rnd}/{i}.png").convert("RGB")
    w, h = im.size
    im = im.resize((768, round(h * 768 / w)), Image.LANCZOS)
    im.save(f"public/art/{i}.webp", "WEBP", quality=82, method=6)
    print("approved", i)

# manifest so the client only requests art that exists (no 404 spam)
import os
have = sorted(f[:-5] for f in os.listdir("public/art") if f.endswith(".webp"))
open("src/client/art-manifest.ts", "w").write("// Generated by scripts/approve-art.py\nexport const ART = new Set<string>(" + repr(have).replace("'", '"') + ");\n")
print("manifest:", len(have), "images")
